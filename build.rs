// Generates the unicode tables the renderer needs from the vendored UCD files in data/ucd.
// Widths and grapheme properties come from the data, never from a hand-written list,
// so emoji and telugu conjuncts take the cells they really take.

use std::fmt::Write as _;
use std::fs;
use std::path::Path;

fn ranges(file: &str, keep: &dyn Fn(&str) -> Option<u8>) -> Vec<(u32, u32, u8)> {
    let text = fs::read_to_string(Path::new("data/ucd").join(file))
        .unwrap_or_else(|e| panic!("data/ucd/{file}: {e}"));
    let mut out = Vec::new();
    for line in text.lines() {
        let line = line.split('#').next().unwrap().trim();
        if line.is_empty() {
            continue;
        }
        let mut parts = line.split(';').map(str::trim);
        let cps = parts.next().unwrap();
        let rest: Vec<&str> = parts.collect();
        let Some(v) = keep(&rest.join(";")) else { continue };
        let (a, b) = match cps.split_once("..") {
            Some((a, b)) => (a, b),
            None => (cps, cps),
        };
        let a = u32::from_str_radix(a, 16).unwrap();
        let b = u32::from_str_radix(b, 16).unwrap();
        out.push((a, b, v));
    }
    merge(out)
}

fn merge(mut v: Vec<(u32, u32, u8)>) -> Vec<(u32, u32, u8)> {
    v.sort();
    let mut out: Vec<(u32, u32, u8)> = Vec::new();
    for r in v {
        if let Some(last) = out.last_mut() {
            if last.2 == r.2 && r.0 <= last.1 + 1 {
                last.1 = last.1.max(r.1);
                continue;
            }
        }
        out.push(r);
    }
    out
}

fn emit2(s: &mut String, name: &str, v: &[(u32, u32, u8)]) {
    writeln!(s, "pub static {name}: [(u32, u32); {}] = [", v.len()).unwrap();
    for (a, b, _) in v {
        writeln!(s, "    (0x{a:X}, 0x{b:X}),").unwrap();
    }
    s.push_str("];\n");
}

fn emit3(s: &mut String, name: &str, v: &[(u32, u32, u8)]) {
    writeln!(s, "pub static {name}: [(u32, u32, u8); {}] = [", v.len()).unwrap();
    for (a, b, c) in v {
        writeln!(s, "    (0x{a:X}, 0x{b:X}, {c}),").unwrap();
    }
    s.push_str("];\n");
}

fn main() {
    // layout recurses once per nested box; deep pages need more than the default 1 mb
    println!("cargo:rustc-link-arg-bins=/STACK:16777216");
    // the window browser's dlls load on first use, so the terminal client never maps them
    for dll in ["d3d11.dll", "dxgi.dll", "dwrite.dll", "d3dcompiler_47.dll", "dwmapi.dll", "gdi32.dll", "user32.dll", "ole32.dll", "oleaut32.dll", "combase.dll", "shell32.dll"] {
        println!("cargo:rustc-link-arg-bins=/DELAYLOAD:{dll}");
    }
    println!("cargo:rustc-link-arg-bins=delayimp.lib");
    embed_webview2_loader();
    for f in ["EAW_wide.txt", "Emoji.txt", "GBP.txt", "InCB.txt", "ZeroWidthGC.txt"] {
        println!("cargo:rerun-if-changed=data/ucd/{f}");
    }

    let mut wide = ranges("EAW_wide.txt", &|p| matches!(p, "W" | "F").then_some(1));
    wide.extend(ranges("Emoji.txt", &|p| (p == "Emoji_Presentation").then_some(1)));
    let wide = merge(wide);

    let mut zero = ranges("ZeroWidthGC.txt", &|p| matches!(p, "Mn" | "Me" | "Cf").then_some(1));
    // hangul medial vowels and final consonants join the previous syllable
    zero.extend(ranges("GBP.txt", &|p| matches!(p, "V" | "T").then_some(1)));
    let zero = merge(zero);

    let pict = ranges("Emoji.txt", &|p| (p == "Extended_Pictographic").then_some(1));

    // grapheme break property, numbered to match text::Gbp
    let gbp = ranges("GBP.txt", &|p| {
        Some(match p {
            "CR" => 1,
            "LF" => 2,
            "Control" => 3,
            "Extend" => 4,
            "ZWJ" => 5,
            "Regional_Indicator" => 6,
            "Prepend" => 7,
            "SpacingMark" => 8,
            "L" => 9,
            "V" => 10,
            "T" => 11,
            "LV" => 12,
            "LVT" => 13,
            _ => return None,
        })
    });

    let incb = ranges("InCB.txt", &|p| {
        Some(match p {
            "InCB;Linker" => 1,
            "InCB;Consonant" => 2,
            "InCB;Extend" => 3,
            _ => return None,
        })
    });

    let mut s = String::from("// generated by build.rs from data/ucd. do not edit.\n");
    emit2(&mut s, "WIDE", &wide);
    emit2(&mut s, "ZERO", &zero);
    emit2(&mut s, "PICT", &pict);
    emit3(&mut s, "GBP", &gbp);
    emit3(&mut s, "INCB", &incb);

    let out = Path::new(&std::env::var("OUT_DIR").unwrap()).join("unicode_tables.rs");
    fs::write(out, s).unwrap();
}

/// Copies the WebView2 loader dll (from the webview2-com-sys crate) where the binary can
/// embed it, so hayate stays one file. An empty file means "look next to the exe".
fn embed_webview2_loader() {
    let out = Path::new(&std::env::var("OUT_DIR").unwrap()).join("WebView2Loader.dll");
    let home = std::env::var("CARGO_HOME").map(std::path::PathBuf::from).unwrap_or_else(|_| Path::new(&std::env::var("USERPROFILE").unwrap_or_default()).join(".cargo"));
    let mut found = None;
    if let Ok(regs) = fs::read_dir(home.join("registry").join("src")) {
        for r in regs.flatten() {
            if let Ok(crates) = fs::read_dir(r.path()) {
                for c in crates.flatten() {
                    let name = c.file_name().to_string_lossy().to_string();
                    if name.starts_with("webview2-com-sys-") {
                        let p = c.path().join("x64").join("WebView2Loader.dll");
                        if p.exists() {
                            found = Some(p);
                        }
                    }
                }
            }
        }
    }
    match found {
        Some(p) => {
            fs::copy(&p, &out).unwrap();
        }
        None => fs::write(&out, b"").unwrap(),
    }
}
